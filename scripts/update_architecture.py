"""Regenerate the source inventory without importing the application or user data."""
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "ARCHITECTURE_SOURCE_MAP.md"
ENTRY_POINTS = {
    "app": "Application / WSGI entry point",
    "download_models": "Optional model installation CLI",
    "scripts.update_architecture": "Architecture maintenance CLI / CI",
    "scripts.check_repository_hygiene": "Repository privacy CLI / CI",
}


def source(path):
    return ast.parse(path.read_text(encoding="utf-8-sig"))


def link(path):
    name = path.relative_to(ROOT).as_posix()
    return f"[{name}](../{name})"


def module_name(path):
    name = path.relative_to(ROOT).with_suffix('').as_posix().replace('/', '.')
    return name.removesuffix('.__init__')


def unreachable_modules(paths):
    """Find unused-file candidates, including constant dynamic/lazy imports.

    Entry points are explicit: a file need not be imported to be a useful CLI.
    This is a maintenance signal, not authorization to delete future files.
    """
    modules = {module_name(path): path for path in paths}
    graph = {}
    for name, path in modules.items():
        edges = set()
        for node in ast.walk(source(path)):
            candidates = []
            if isinstance(node, ast.Import):
                candidates = [alias.name for alias in node.names]
            elif isinstance(node, ast.ImportFrom):
                base = node.module or ''
                if node.level:
                    package = name if path.name == '__init__.py' else name.rpartition('.')[0]
                    parts = package.split('.')
                    package = '.'.join(parts[:len(parts) - node.level + 1])
                    base = '.'.join(part for part in (package, base) if part)
                candidates = [base] + [base + '.' + alias.name for alias in node.names]
            elif (isinstance(node, ast.Call) and node.args
                  and isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str)):
                if ((isinstance(node.func, ast.Name) and node.func.id in ('lazy_module', '__import__'))
                        or (isinstance(node.func, ast.Attribute) and node.func.attr == 'import_module')):
                    candidates = [node.args[0].value]
            edges.update(candidate for candidate in candidates if candidate in modules)
        graph[name] = edges
    reached, pending = set(), list(ENTRY_POINTS)
    while pending:
        name = pending.pop()
        if name not in reached:
            reached.add(name)
            pending.extend(graph.get(name, set()) - reached)
    return sorted(name for name in modules if name not in reached)


def generate():
    modules = sorted([*ROOT.glob("*.py"), *(ROOT / "routes").glob("*.py"),
                      *(ROOT / "scripts").glob("*.py")])
    local = {p.stem for p in modules}
    lines = ["# Architecture source map", "",
             "Generated by `python scripts/update_architecture.py`. Source-only inventory; "
             "does not load `.env`, import processors, inspect private files, or download models.", "",
             "## Python module coverage", "",
             "Every top-level application module, blueprint module and maintenance script is listed. "
             "Imports below show direct references to project modules; dynamically loaded optional engines "
             "and external packages are described in the detailed architecture.", "",
             "| Module | Direct local imports | Top-level classes |",
             "|---|---|---|"]
    routes = []
    for path in modules:
        tree = source(path)
        imports, classes = set(), []
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                imports.update(a.name for a in node.names if a.name.split('.')[0] in local)
            elif isinstance(node, ast.ImportFrom) and node.module:
                if node.module.split('.')[0] in local or node.level:
                    imports.add('.' * node.level + node.module)
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                for dec in node.decorator_list:
                    if (isinstance(dec, ast.Call) and isinstance(dec.func, ast.Attribute)
                            and dec.func.attr == "route" and dec.args):
                        route = ast.literal_eval(dec.args[0])
                        methods = next((ast.literal_eval(k.value) for k in dec.keywords
                                        if k.arg == "methods"), ["GET"])
                        routes.append((path, route, ", ".join(methods), node.name))
        classes = [n.name for n in tree.body if isinstance(n, ast.ClassDef)]
        lines.append(f"| {link(path)} | {', '.join(f'`{n}`' for n in sorted(imports)) or '—'} "
                     f"| {', '.join(f'`{n}`' for n in classes) or '—'} |")
    lines.extend(["", "## Entry points and unused-file check", "",
                  "The maintenance check traces direct imports, relative package imports and constant "
                  "`import_module` / `__import__` / `lazy_module` calls from these explicit entry points. "
                  "Optional imports count as used. Computed plugin imports and external consumers "
                  "require manual review; no files are automatically deleted.", "",
                  "| Entry point | Purpose |", "|---|---|"])
    for name, purpose in ENTRY_POINTS.items():
        lines.append(f"| `{name}` | {purpose} |")
    unused = unreachable_modules(modules)
    lines.extend(["", "Unreachable Python module candidates: " + (', '.join(unused) if unused else '**none**') + "."])
    if unused:
        raise ValueError("Review unused Python files or register legitimate entry points: " + ', '.join(unused))
    lines.extend(["", "## HTTP route inventory", "",
                  "Methods are declared methods (Flask's implicit HEAD/OPTIONS omitted). "
                  "The framework static-file route is implicit. No SSE or WebSocket endpoint is declared.", "",
                  "| Route | Methods | Handler | Source |", "|---|---|---|---|"])
    for path, route, methods, handler in sorted(routes, key=lambda r: r[1]):
        lines.append(f"| `{route}` | {methods} | `{handler}` | {link(path)} |")
    lines.extend(["", "## Copilot tool registry", "",
                  "Generated from `ToolSpec` declarations in `agent_planner.py`. "
                  "Editor-only HTTP operations can exist outside this registry.", "",
                  "| Tool identifier | Owning sub-agent | Label |", "|---|---|---|"])
    tools = []
    for node in ast.walk(source(ROOT / "agent_planner.py")):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "ToolSpec":
            tools.append(tuple(ast.literal_eval(a) for a in node.args[:3]))
    for tool, agent, label in sorted(tools):
        lines.append(f"| `{tool}` | `{agent}` | {label} |")
    lines.extend(["", f"Declared copilot tools: **{len(tools)}**.", "",
                  "## Browser controllers and templates", "",
                  "Vendored third-party JavaScript is excluded from this first-party inventory.", "",
                  "| Source | Kind |", "|---|---|"])
    for path in sorted([p for p in (ROOT / "static").rglob("*.js") if "vendor" not in p.parts]
                       + list((ROOT / "templates").glob("*.html"))):
        lines.append(f"| {link(path)} | {'Template / partial' if path.suffix == '.html' else 'Browser controller'} |")
    lines.extend(["", "## Built-in skill workflows", "",
                  "These versioned instructions expand into validated tools. Personal workflows live "
                  "in ignored `user_skills/` (or `COPILOT_USER_SKILLS_DIR`).", ""])
    for path in sorted((ROOT / "skills").glob("*/SKILL.md")):
        lines.append(f"- {link(path)}")
    lines.extend(["", "## Public configuration keys", "",
                  "Only key names from `.env.example` are listed; local values are never read.", ""])
    for line in (ROOT / ".env.example").read_text(encoding="utf-8-sig").splitlines():
        if line.strip() and not line.lstrip().startswith("#") and "=" in line:
            lines.append(f"- `{line.split('=', 1)[0].strip()}`")
    return '\n'.join(lines) + '\n'


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the inventory needs regeneration")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("Architecture source map is stale: run python scripts/update_architecture.py")
        print("Architecture source map is current.")
    else:
        OUTPUT.write_text(content, encoding="utf-8")
        print("Updated docs/ARCHITECTURE_SOURCE_MAP.md")
